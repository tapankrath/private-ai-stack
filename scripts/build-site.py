#!/usr/bin/env python3
"""Build site/advisor-data.js (from config/*.yaml and profiles/*.yaml) and site/guide.html
(from docs/SETUP_GUIDE.md).

The public Advisor page (site/index.html) runs the JavaScript port of the engine entirely in
the visitor's browser. Re-run this after editing the catalog, rules, prices or the guide:

    python scripts/build-site.py
"""
from __future__ import annotations

import datetime as dt
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent


def _default(o):
    if isinstance(o, (dt.date, dt.datetime)):
        return o.isoformat()[:10]
    raise TypeError(f"cannot serialize {type(o)}")


def build() -> str:
    cfg = ROOT / "config"
    data = {name: yaml.safe_load((cfg / f"{file}.yaml").read_text())
            for name, file in [("rules", "rules"), ("catalog", "model_catalog"), ("hardware", "hardware_reference"),
                               ("runtimes", "runtimes"), ("pricing", "pricing")]}
    profiles = {}
    for p in sorted((ROOT / "profiles").glob("*.yaml")):
        if p.name.startswith("_"):
            continue
        raw = yaml.safe_load(p.read_text())
        raw.pop("expected", None)
        profiles[raw["profile_id"]] = raw
    data["profiles"] = profiles
    body = json.dumps(data, default=_default, separators=(",", ":"), sort_keys=False)
    return ("/* Generated by scripts/build-site.py from config/*.yaml and profiles/*.yaml. Do not edit. */\n"
            f"globalThis.ADVISOR_DATA = {body};\n")


GUIDE_TEMPLATE = (ROOT / "site" / "guide.template.html")


def build_guide() -> str | None:
    """Render the setup guide (CommonMark + tables, as GitHub does). None if markdown-it-py is missing."""
    try:
        from markdown_it import MarkdownIt
    except ImportError:
        return None
    import html
    import re

    body = MarkdownIt("gfm-like", {"linkify": False}).render((ROOT / "docs" / "SETUP_GUIDE.md").read_text())
    toc = []

    def anchor(m):
        level, inner = m.group(1), m.group(2)
        slug = re.sub(r"[^a-z0-9]+", "-", html.unescape(re.sub(r"<[^>]+>", "", inner)).lower()).strip("-")
        if level == "2":
            toc.append(f'<li><a href="#{slug}">{inner}</a></li>')
        return f'<h{level} id="{slug}">{inner}</h{level}>'

    body = re.sub(r"<h([23])>(.*?)</h\1>", anchor, body)
    return GUIDE_TEMPLATE.read_text().replace("<!--TOC-->", "".join(toc)).replace("<!--BODY-->", body)


PAGE_HEAD = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<style>:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}img{max-width:100%}[hidden]{display:none!important}</style>
"""


def wrap_page(fragment: str) -> str:
    """site/index.html is a page fragment (the Claude artifact host adds the document shell).
    For GitHub Pages, add the shell here: doctype, charset, viewport."""
    i = fragment.index("</style>") + len("</style>")
    return PAGE_HEAD + fragment[:i] + "\n</head>\n<body>\n" + fragment[i:] + "\n</body>\n</html>\n"


def build_pages(out_dir: Path) -> None:
    import shutil
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    for f in (ROOT / "site").iterdir():
        if f.is_file() and f.name != "guide.template.html":
            shutil.copy2(f, out_dir / f.name)
    (out_dir / "index.html").write_text(wrap_page((ROOT / "site" / "index.html").read_text()))


if __name__ == "__main__":
    out = ROOT / "site" / "advisor-data.js"
    out.write_text(build())
    print(f"wrote {out} ({out.stat().st_size // 1024} KB)", file=sys.stderr)
    guide = build_guide()
    if guide is None:
        print("markdown-it-py not installed: kept the existing site/guide.html (pip install markdown-it-py to rebuild it)", file=sys.stderr)
    else:
        (ROOT / "site" / "guide.html").write_text(guide)
        print("wrote site/guide.html", file=sys.stderr)
    if "--pages-out" in sys.argv:
        dest = Path(sys.argv[sys.argv.index("--pages-out") + 1]).resolve()
        build_pages(dest)
        print(f"wrote the GitHub Pages site to {dest}", file=sys.stderr)
